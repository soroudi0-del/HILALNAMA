// طیف رنگ ۶پله‌ای مرجع، از بهترین (رؤیت آسان) تا بدترین (غیرممکن)
var SEVERITY_COLOR_SCALE = [
  colors.catA, colors.catB, colors.catC, colors.catD, colors.catE, colors.catF,
];

// ------------------------------------------------------------
// استثنای نقطه‌ای روی فرمول نسبی (بازبینی جاری):
// در Odeh (['A','B','C','D']) فرمول نسبی حرف 'B' را روی idx=1/3=0.33
// می‌گذارد که به نزدیک‌ترین پله از ۶ پله گرد می‌شود به پله‌ی catC
// (زرد روشن #ffe17b) — یعنی B در Odeh با رنگ C نمایش داده می‌شد.
// اینجا صراحتاً پین می‌شود به خودِ catB (#84BD00) بدون این‌که فرمول
// نسبی، یا رنگ A/C/D در Odeh، یا هیچ حرفی در سایر معیارها تغییر کند.
// اگر ترکیب (crit, cat) در این جدول نباشد، مسیر عادی (فرمول نسبی)
// اجرا می‌شود.
// ------------------------------------------------------------
var CAT_COLOR_OVERRIDES = {
  odeh: {
    B: colors.catB,
  },
};

// نگاشت رده‌ی رؤیت‌پذیری به رنگ — جایگزین MoonCalculator.getCatColor
// که رنگ‌های قدیمی (#00CC44 و...) را مستقیم در کد داشت.
//
// پارامتر crit اختیاری است: اگر پاس داده نشود (سازگاری با
// فراخوانی‌های قدیمی‌تر)، رفتار قبلی (رنگ فقط بر اساس حرف، روی
// مقیاس ۶پله‌ای Yallop) حفظ می‌شود — چون Yallop تنها معیاری است که
// از هر ۶ حرف استفاده می‌کند و این نگاشت پیش‌فرض منطقی‌ترین است.
function getCatColor(cat, crit) {
  if (!cat) return colors.catUnknown;

  var override = crit && CAT_COLOR_OVERRIDES[crit] && CAT_COLOR_OVERRIDES[crit][cat];
  if (override) return override;

  var letters = (crit && CRIT_LETTERS_BY_SEVERITY[crit]) || CRIT_LETTERS_BY_SEVERITY.yallop;
  var idx = letters.indexOf(cat);
  if (idx === -1) return colors.catUnknown;

  // موقعیت نسبی (۰ تا ۱) این حرف در طیف شدت خودِ معیار را به
  // نزدیک‌ترین پله‌ی مقیاس ۶رنگی مرجع نگاشت می‌کند.
  var ratio = letters.length > 1 ? idx / (letters.length - 1) : 0;
  var scaleIdx = Math.round(ratio * (SEVERITY_COLOR_SCALE.length - 1));
  return SEVERITY_COLOR_SCALE[scaleIdx];
}


